import Foundation

public struct MediaMTXConfigOptions: Equatable {
  public var includeMoqKey: Bool

  public init(includeMoqKey: Bool = true) {
    self.includeMoqKey = includeMoqKey
  }
}

public enum MediaMTXConfigWriter {
  public static let apiAddress = "127.0.0.1:9997"
  public static let rtspAddress = "127.0.0.1:8554"

  public static func yaml(
    settings: AppSettings,
    advertisedHost: String? = nil,
    options: MediaMTXConfigOptions = MediaMTXConfigOptions()
  ) -> String {
    let udp: String
    let tcp: String
    switch settings.networkMode {
    case .auto:
      udp = ":\(settings.icePort)"
      tcp = ":\(settings.icePort)"
    case .udpOnly:
      udp = ":\(settings.icePort)"
      tcp = ""
    case .tcpOnly:
      udp = ""
      tcp = ":\(settings.icePort)"
    }

    var lines = [
      "# Generated by RoomCast. Rewritten on every Start.",
      "logLevel: \(settings.logLevel.rawValue)",
      "api: yes",
      "apiAddress: \(apiAddress)",
      "rtsp: yes",
      "rtspAddress: \(rtspAddress)",
      "rtspTransports: [tcp]",
      "rtmp: no",
      "hls: no",
      "srt: no",
    ]
    if options.includeMoqKey {
      lines.append("moq: no")
    }
    let webrtcHTTP = webrtcHTTPPort(
      listenerPort: settings.listenerPort, icePort: settings.icePort)
    lines += [
      "webrtc: yes",
      // Phones open the app's page on the listener port. MediaMTX answers
      // WHEP on loopback, and the app forwards it.
      "webrtcAddress: 127.0.0.1:\(webrtcHTTP)",
      "webrtcLocalUDPAddress: \(yamlScalar(udp))",
      "webrtcLocalTCPAddress: \(yamlScalar(tcp))",
      "webrtcIPsFromInterfaces: yes",
    ]
    if let advertisedHost, isSafeHost(advertisedHost) {
      lines.append("webrtcAdditionalHosts: ['\(advertisedHost)']")
    }
    // writeQueueSize stays at MediaMTX's default (512 packets, about 10 s of
    // 20 ms audio). That queue is not what inserts the regular click.
    // useAbsoluteTimestamp stays off so RTSP keeps the publisher's timeline
    // instead of restamping onto the wall clock.
    lines += [
      "paths:",
      "  \(settings.streamName):",
      "    source: publisher",
      "    maxReaders: \(settings.maxListeners)",
    ]
    return lines.joined(separator: "\n") + "\n"
  }

  /// Loopback port for MediaMTX's WebRTC HTTP server. The public listener
  /// port belongs to the app, which serves `/` and forwards WHEP here.
  public static func webrtcHTTPPort(listenerPort: Int, icePort: Int) -> Int {
    let blocked: Set<Int> = [listenerPort, icePort, WatchedPorts.rtsp, WatchedPorts.api]
    var candidate = listenerPort + 10_000
    if !(1...65_535).contains(candidate) {
      candidate = 18_889
    }
    var steps = 0
    while blocked.contains(candidate) {
      candidate += 1
      if candidate > 65_535 { candidate = 1 }
      steps += 1
      if steps > 8 { return 18_889 }
    }
    return candidate
  }

  public static func topLevelKeys(in yaml: String) -> Set<String> {
    var keys = Set<String>()
    for line in yaml.split(separator: "\n") {
      let trimmed = line.trimmingCharacters(in: .whitespaces)
      if trimmed.isEmpty || trimmed.hasPrefix("#") { continue }
      guard let colon = trimmed.firstIndex(of: ":") else { continue }
      let key = String(trimmed[..<colon])
      if key.allSatisfy({ $0.isLetter || $0.isNumber }) {
        keys.insert(key)
      }
    }
    return keys
  }

  private static func yamlScalar(_ value: String) -> String {
    value.isEmpty ? "''" : value
  }

  private static func isSafeHost(_ host: String) -> Bool {
    !host.isEmpty
      && host.allSatisfy { character in
        character.isLetter || character.isNumber || character == "." || character == "-"
          || character == ":"
      }
  }
}
